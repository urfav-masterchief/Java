package com.geeks;
import java.util.Scanner;
public class Increment_Decrement {
    public static void main(String[] args){
        int y = 7;
        System.out.println(y);
        y += 56;
        System.out.println(y);
        y *= 3;
        System.out.println(y);
        y -= 182;
        System.out.println(y);
        System.out.println();

        int x = 10;
        int z = x++;
        System.out.println(x+" "+z);



    }
}
